"""
Defines the tables for the RAG (Retrieval-Augmented Generation) knowledge
base: documents the user has added (notes, project docs, FAQs...) and the
smaller "chunks" each document gets split into for searching.

Quick concepts:
- "chunk": documents are split into smaller pieces (a few paragraphs each)
  before embedding, because embedding models work best on focused pieces
  of text, and because search results are more precise when you retrieve
  "the 3 relevant paragraphs" instead of "the whole 10-page document".
- "embedding": a list of numbers (a vector) that represents what a piece
  of text MEANS, generated by an AI model. Two pieces of text with similar
  meaning end up with similar vectors - this is what makes searching by
  meaning (not just exact keywords) possible.
- "pgvector": a PostgreSQL extension that adds a proper "vector" column
  type and fast similarity search, so this all runs in the same database
  as everything else in the app (no separate vector database needed).
"""

from pgvector.sqlalchemy import Vector
from sqlalchemy import Column, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

from app.core.database import Base

# Must match the output_dimensionality used when generating embeddings
# (see app/services/embedding_service.py) - if you ever change one, you
# must change the other AND re-embed existing documents.
EMBEDDING_DIMENSIONS = 768


class Document(Base):
    __tablename__ = "documents"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False, index=True)
    title = Column(String, nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    chunks = relationship("DocumentChunk", back_populates="document", cascade="all, delete-orphan")


class DocumentChunk(Base):
    __tablename__ = "document_chunks"

    id = Column(Integer, primary_key=True, index=True)
    document_id = Column(Integer, ForeignKey("documents.id"), nullable=False, index=True)
    # Denormalized (also on the parent Document) so a knowledge search can
    # filter straight to "this user's chunks" in one simple query, without
    # having to join through documents every time.
    user_id = Column(Integer, ForeignKey("users.id"), nullable=False, index=True)
    chunk_index = Column(Integer, nullable=False)
    content = Column(Text, nullable=False)
    embedding = Column(Vector(EMBEDDING_DIMENSIONS), nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    document = relationship("Document", back_populates="chunks")